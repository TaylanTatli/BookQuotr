/**
 * Get a human-readable language name from a raw code.
 * Falls back to the original code if not found.
 */
export function getLanguageName(code: string | null | undefined, locale: string): string {
  if (!code) return "";
  const normalized = code.toLowerCase().trim();
  const entry = LANGUAGE_MAP[normalized];
  if (!entry) return code; // fallback to raw code
  return locale === "tr" ? entry.tr : entry.en;
}
